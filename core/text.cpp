/* Other code points. */
static const struct {
  unsigned cp;
  unsigned char c;
} U2cPairs[] = { { 0x150, 0x99 }, { 0x151, 0x94 }, /* O / o with double acute -> umlaut */
                 { 0x170, 0x9A }, { 0x171, 0x81 }, /* U / u with double acute -> umlaut */
                 { 0x2013, '-' }, { 0x2014, '-' }, { 0x2018, 0x27 }, { 0x2019, 0x27 }, { 0x201A, ',' }, { 0x201C, '"' },
                 { 0x201D, '"' }, { 0x201E, '"' }, { 0x2022, 7 },    { 0x2026, '.' },  { 0, 0 } };

static unsigned char mapCp( unsigned cp ) {
  if ( cp < 0x80 ) return (unsigned char)cp;
  if ( cp < 0xA0 ) return '?';
  if ( cp < 0x100 ) return U2cA0[cp - 0xA0];
  for ( int i = 0; U2cPairs[i].cp; i++ ) {
    if ( U2cPairs[i].cp == cp ) return U2cPairs[i].c;
  }
  return '?';
}

static unsigned decodeUtf8( unsigned char *s, unsigned char lead, int &advance ) {
  if ( lead < 0xE0 ) {
    advance = 1;
    return ( ( lead & 0x1F ) << 6 ) | ( s[0] & 0x3F );
  }
  if ( lead < 0xF0 ) {
    if ( ( s[1] & 0xC0 ) != 0x80 ) { advance = 0; return 0; }
    advance = 2;
    return ( (unsigned)( lead & 0x0F ) << 12 ) | ( ( s[0] & 0x3F ) << 6 ) | ( s[1] & 0x3F );
  }
  advance = 0;
  while ( ( *s & 0xC0 ) == 0x80 ) { s++; advance++; }
  return 0xFFFD;
}

unsigned utf8To437( char *buf ) {
  unsigned char *s = (unsigned char *)buf;
  unsigned char *d = s;
  unsigned char c;
  while ( ( c = *s++ ) != 0 ) {
    if ( c < 0xC2 || c > 0xF4 || ( s[0] & 0xC0 ) != 0x80 ) {
      *d++ = c;
      continue;
    }
    int skip;
    unsigned cp = decodeUtf8( s, c, skip );
    if ( skip == 0 ) { *d++ = c; continue; }
    s += skip;
    if ( cp != 0xFEFF ) *d++ = ( cp == 0xFFFD ) ? '?' : mapCp( cp );
  }
  *d = 0;
  return d - (unsigned char *)buf;
}

