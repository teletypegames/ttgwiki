char *cp437ToUtf8( char *d, const char *s ) {
  for ( ; *s; s++ ) {
    unsigned char c = *s;
    if ( c < 0x80 ) {
      *d++ = c;
      continue;
    }
    unsigned u = C2u[c - 0x80];
    if ( u < 0x800 ) *d++ = (char)( 0xC0 | ( u >> 6 ) );
    else {
      *d++ = (char)( 0xE0 | ( u >> 12 ) );
      *d++ = (char)( 0x80 | ( ( u >> 6 ) & 0x3F ) );
    }
    *d++ = (char)( 0x80 | ( u & 0x3F ) );
  }
  return d;
}

const char *skipBom( const char *s ) {
  if ( (unsigned char)s[0] == 0xEF && (unsigned char)s[1] == 0xBB && (unsigned char)s[2] == 0xBF ) s += 3;
  return s;
}
