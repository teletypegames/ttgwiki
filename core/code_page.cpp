bool codePageOf( unsigned number, CodePage &cp ) {
  if ( number == 437 ) cp = CodePage437;
  else if ( number == 852 ) cp = CodePage852;
  else return false;
  return true;
}

static unsigned char mapCp( unsigned cp, const CodePair *pairs, int count ) {
  if ( cp < 0x80 ) return (unsigned char)cp;
  int lo = 0, hi = count - 1;
  while ( lo <= hi ) {
    int mid = ( lo + hi ) / 2;
    if ( pairs[mid].cp == cp ) return pairs[mid].c;
    if ( pairs[mid].cp < cp ) lo = mid + 1;
    else hi = mid - 1;
  }
  return '?';
}

static int countOf( const CodePair *pairs ) {
  int n = 0;
  while ( pairs[n].cp ) n++;
  return n;
}

/* The code point of the sequence after its lead byte, and its length after the lead;
   0 when it is not valid UTF-8. */
static unsigned decode( const unsigned char *s, unsigned char lead, int &advance ) {
  int extra = lead < 0xE0 ? 1 : lead < 0xF0 ? 2 : 3;
  unsigned cp = lead & ( lead < 0xE0 ? 0x1F : lead < 0xF0 ? 0x0F : 0x07 );
  for ( int i = 0; i < extra; i++ ) {
    if ( ( s[i] & 0xC0 ) != 0x80 ) {
      advance = 0;
      return 0;
    }
    cp = ( cp << 6 ) | ( s[i] & 0x3F );
  }
  advance = extra;
  return extra == 3 ? 0xFFFD : cp;
}

unsigned utf8ToCodePage( char *buf, CodePage page ) {
  const CodePair *pairs = page == CodePage852 ? To852 : To437;
  int count = countOf( pairs );
  unsigned char *s = (unsigned char *)buf;
  unsigned char *d = s;
  unsigned char c;
  while ( ( c = *s++ ) != 0 ) {
    if ( c < 0xC2 || c > 0xF4 || ( s[0] & 0xC0 ) != 0x80 ) {
      *d++ = c;
      continue;
    }
    int skip;
    unsigned cp = decode( s, c, skip );
    if ( skip == 0 ) {
      *d++ = c;
      continue;
    }
    s += skip;
    if ( cp != 0xFEFF ) *d++ = mapCp( cp, pairs, count );
  }
  *d = 0;
  return d - (unsigned char *)buf;
}

unsigned char foldLetter( unsigned char c, CodePage page ) {
  if ( c >= 'a' && c <= 'z' ) return c - 'a' + 'A';
  if ( c < 0x80 ) return c;
  return ( page == CodePage852 ? Fold852 : Fold437 )[c - 0x80];
}
